using System.Globalization;
using CineSpace.Client;
using CineSpace.Client.Services;
using Microsoft.AspNetCore.Components.Web;
using Microsoft.AspNetCore.Components.WebAssembly.Hosting;
var culture = CultureInfo.GetCultureInfo("es-BO");
CultureInfo.DefaultThreadCurrentCulture = culture;
CultureInfo.DefaultThreadCurrentUICulture = culture;
var builder = WebAssemblyHostBuilder.CreateDefault(args);
builder.RootComponents.Add<App>("#app");
builder.RootComponents.Add<HeadOutlet>("head::after");
var apiUrl = builder.Configuration["Api:BaseUrl"];
if (builder.HostEnvironment.IsDevelopment() && new Uri(builder.HostEnvironment.BaseAddress).Scheme == Uri.UriSchemeHttp)
    apiUrl = builder.Configuration["Api:HttpBaseUrl"] ?? apiUrl;
var baseUri = new Uri(string.IsNullOrWhiteSpace(apiUrl) ? builder.HostEnvironment.BaseAddress : apiUrl);
builder.Services.AddScoped(_ => new HttpClient(new BrowserCredentialsHandler { InnerHandler = new HttpClientHandler() }) { BaseAddress = baseUri });
builder.Services.AddScoped<ISistemaClient, SistemaClient>();
builder.Services.AddScoped<ApiCine>();
builder.Services.AddScoped<ActividadSolicitudes>();
builder.Services.AddScoped<UsuarioService>();
builder.Services.AddScoped<TrabajadorService>();
builder.Services.AddScoped<PeliculaService>();
builder.Services.AddScoped<SalaService>();
builder.Services.AddScoped<CatalogosService>();
builder.Services.AddScoped<FuncionesService>();
builder.Services.AddScoped<TicketSalesService>();
builder.Services.AddScoped<BannersService>();
builder.Services.AddScoped<EstrenosService>();
builder.Services.AddScoped<PedidosConfiteriaService>();
builder.Services.AddScoped<AsientoService>();
builder.Services.AddScoped<AuthDialogService>();
builder.Services.AddScoped<LogoutDialogService>();
builder.Services.AddScoped<SessionTransitionService>();
builder.Services.AddScoped<QRService>();
var host = builder.Build();
await host.RunAsync();
